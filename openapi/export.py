"""Export the API contract to checked-in files.

There are two apps, so there are two documents — and only one of them is
published:

- ``openapi/openapi.json`` — the REGIONAL API. This is the contract: both SDKs in
  ``clients/`` and ``mcp/tools.json`` are generated from it, so an integrator
  holds one base URL and one token and no published method can express a call to
  the other plane. ``documentation/openapi.json`` is the same document plus the
  region base URLs and the auth scheme, which is what the rendered API reference
  reads and what a generator input must not carry.
- ``openapi/control.json`` — the CONTROL API, published nowhere. Its one consumer
  is the dashboard's client in ``frontend/lib/control/``, generated by the same
  generator. Hand-maintaining those 17 endpoints and their types in the frontend
  is the drift ``services/user/tenants.py`` exists to warn about.

Plus the two agent-facing artifacts, both regional:

- ``mcp/tools.json`` — the functions from ``api.dataplane.functions``, the tool
  list the MCP server serves.
- ``mcp/SKILL.md`` — ``backend/services/copilot/skill.md``, the platform
  knowledge CoPilot is prompted with, packaged as a skill.

The last two are what keep an external Claude Code or Codex on the same footing
as our own CoPilot: same functions, same knowledge, one generator.

Usage:
    PYTHONPATH=backend python openapi/export.py

Uses two minimal in-memory Settings — one per node — so export needs no filled
config file. Each app asserts its own role at import, which is exactly why the
settings are swapped between the two imports below rather than one object being
made to satisfy both.
"""

