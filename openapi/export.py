# An MCP client loads the whole tool list before the user has typed anything, so
# this is a floor on what our server costs a session. It reached ~600k
# characters once — more than a 200k-context client can hold, empty — for the
# honest reason that nothing counted it.
#
# Today it is well under that, because every function defers its argument schema
# to `describe_function` and only its name and description are carried. The cap
# stays where it is so that re-inlining one `DEFERRED_SCHEMAS` document (39k on
# its own) fails the export that does it rather than three releases later.
MAX_TOOL_SURFACE_CHARS = 150_000

SKILL_FRONTMATTER = """---
name: talqing
description: >-
  Build, publish and operate Talqing AI voice, video and text agents — agent
  config and model stack, custom tools and their operation trees, MCP and
  messaging integrations, phone numbers, secrets and webhooks, plus placing
  calls and reading back transcripts, cost and latency. Use whenever working
  against a Talqing workspace through the talqing MCP server.
---
"""


def _generated_note(source: str) -> str:
    return (
        f"<!-- Generated by openapi/export.py from {source}. Edit that file, "
        "then re-run the export. -->"
    )


def _tools() -> dict:
    """The MCP tool list, straight from the function registry.

    Path parameters are the `{name}` placeholders in `path`; every other
    top-level argument is a query parameter, and `body` is the JSON body. That
    is all a client needs to turn a tool call into the HTTP request.
    """
    return {
        "api_version": dataplane_app.version,
        "api_prefix": "/v1",
        "tools": [
            {
                "name": fn.name,
                "method": fn.method,
                "path": fn.path,
                "description": fn.summary,
                "role": fn.role,
                "read_only": fn.read_only,
                "parameters": fn.parameters,
            }
            for fn in registry().values()
        ],
    }


def _size(value) -> int:
    return len(json.dumps(value, separators=(",", ":")))


def _check_tool_surface(tools: dict) -> int:
    """Refuse to export a tool list too big for the context of the client loading it.

    Weighs what the server actually hands a client on connect: each tool's
    argument schema AND its description. The descriptions are nearly half of it,
    and they are the half that creeps — every new endpoint adds one, and a
    docstring has no natural ceiling the way a schema does.
    """
    total = sum(_size(tool) for tool in tools["tools"])
    if total <= MAX_TOOL_SURFACE_CHARS:
        return total
    biggest = sorted(tools["tools"], key=_size, reverse=True)[:5]
    raise SystemExit(
        f"the tool surface is {total:,} characters, over the "
        f"{MAX_TOOL_SURFACE_CHARS:,} ceiling — and an MCP client loads all of it "
        "before the user types anything.\nThe largest are:\n"
        + "\n".join(
            f"  {t['name']:<32}{_size(t):>7,}"
            f"  ({_size(t['parameters']):,} schema, {_size(t['description']):,} description)"
            for t in biggest
        )
        + "\nDefer the type a schema carries (api.dataplane.functions.DEFERRED_SCHEMAS), or "
        "shorten the route docstring, rather than raising the ceiling."
    )


def _control_document() -> dict:
    """Build the control app's document, with control's own settings installed.

    Imported here rather than at module scope: each ``main.py`` asserts at import
    that the loaded config is for its own role, so the two apps cannot be built
    under one settings object — which is the assertion doing its job.
    """
    configure_settings(CONTROL_SETTINGS)
    from api.control.main import app as control_app

    document = control_app.openapi()
    configure_settings(REGION_SETTINGS)
    return document


def _no_leak(document: dict, forbidden: tuple[str, ...], name: str) -> None:
    """Two documents, and neither may carry the other's paths.

    Cheap, and it is the check that would have caught a route left on the wrong
    app: a control route in the published document reaches every SDK and the MCP
    tool list, which is exactly what the split exists to prevent.
    """
    leaked = sorted(
        path for path in document.get("paths", {}) if path.startswith(forbidden)
    )
    if leaked:
        raise SystemExit(
            f"{name} carries paths belonging to the other plane: {', '.join(leaked)}"
        )


def main() -> None:
    tools = _tools()
    surface = _check_tool_surface(tools)

    published = dataplane_app.openapi()
    _no_leak(
        published,
        ("/v1/orgs", "/v1/org", "/v1/tokens", "/v1/auth", "/v1/regions"),
        "openapi.json",
    )
    control = _control_document()
    _no_leak(
        control,
        ("/v1/agents", "/v1/calls", "/v1/tools", "/v1/billing/credits"),
        "control.json",
    )

    OPENAPI_OUT.write_text(json.dumps(published, indent=2, sort_keys=True) + "\n")
    CONTROL_OUT.write_text(json.dumps(control, indent=2, sort_keys=True) + "\n")
    DOCS_OUT.write_text(
        json.dumps(
            {**published, "servers": DOCS_SERVERS, "security": [{"BearerAuth": []}]},
            indent=2,
            sort_keys=True,
        )
        + "\n"
    )
    # sort_keys, like the OpenAPI documents above: Pydantic emits each function's
    # `$defs` in whatever order it walked the models, which varies run to run and
    # reordered ~400 lines of a checked-in artifact every export, burying the one
    # line that actually changed.
    TOOLS_OUT.write_text(json.dumps(tools, indent=2, sort_keys=True) + "\n")
    SKILL_OUT.write_text(
        f"{SKILL_FRONTMATTER}\n{_generated_note(SKILL_PATH.relative_to(REPO))}\n\n{skill()}\n"
    )
    for path in (OPENAPI_OUT, CONTROL_OUT, DOCS_OUT, TOOLS_OUT, SKILL_OUT):
        print(f"wrote {path.relative_to(REPO)}")
    # Printed every export, because the only reason this grew to 600k characters
    # unnoticed is that no one ever saw the number.
    print(
        f"\non connect an MCP client loads {len(tools['tools'])} tools "
        f"({surface:,} of {MAX_TOOL_SURFACE_CHARS:,} chars) "
        f"plus {len(skill()):,} chars of SKILL.md"
    )


if __name__ == "__main__":
    main()
