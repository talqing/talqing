#!/usr/bin/env python3
"""Generate the Python SDK's API surface from ``openapi/openapi.json``.

``src/talqing/gen`` is checked in and never edited by hand. Regenerate with

    python clients/python/generate.py

after re-running ``openapi/export.py``; ``--check`` asserts the tree on disk is
still what the document generates instead of writing it.

The shape is the one ``backend/api/sdk_surface.py`` declares. A dotted operation
id is a path through the client, so ``agents.versions.rollback`` is
``client.agents.versions.rollback(...)`` here and the same call in the
TypeScript SDK. Each part is snake_cased on the way in — ``telephony.phoneNumbers``
becomes ``client.telephony.phone_numbers`` — because that is the same name
written the way Python writes names.

Three rules decide the rest:

- **A schema becomes a TypedDict, and a response is the decoded JSON.** Nothing
  is validated or coerced on arrival, so the SDK cannot reject a payload the API
  considers valid, and ``httpx`` stays the only runtime dependency.
- **A request body is expanded into keyword arguments.** No body property
  collides with a path or query parameter anywhere in the document — the
  generator asserts it — so ``agents.create(name=..., config=...)`` is
  unambiguous.
- **What the caller does not pass is not sent.** Optional arguments default to
  ``OMIT``, never to the server's own default, because ``null`` is a real value
  on several PATCH bodies (``orgs.update(retention_days=None)`` means "keep
  everything forever") and has to stay distinguishable from "leave it alone".
"""

